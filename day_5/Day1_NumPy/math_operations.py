import numpy as np

a = np.array([2, 4, 6, 8])
b = np.array([1, 3, 5, 7])

print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)
print("Power:", a ** 2)
print("Square Root:", np.sqrt(a))
print("Maximum:", np.max(a))
print("Minimum:", np.min(a))
print("Average:", np.mean(a))
print("Sum:", np.sum(a))
print("Median:", np.median(a))
print("Standard Deviation:", np.std(a))
